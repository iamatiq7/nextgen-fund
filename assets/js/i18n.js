  function detect() {
    try { var s = localStorage.getItem('ngf_lang'); if (s && (s === 'en' || s === 'bn')) return s; } catch (e) {}
    return 'en';
  }

  var L = {
    lang: detect(),
    t: function (k, vars) {
      var s = (dict[L.lang] && dict[L.lang][k]) || dict.en[k] || k;
      if (vars) Object.keys(vars).forEach(function (v) { s = s.split('{' + v + '}').join(String(vars[v])); });
      return s;
    },
    set: function (l) {
      if (l !== 'en' && l !== 'bn') return;
      L.lang = l;
      try { localStorage.setItem('ngf_lang', l); } catch (e) {}
    },
    toggle: function () { L.set(L.lang === 'bn' ? 'en' : 'bn'); },
    apply: function (root) {
      root = root || document;
      document.documentElement.setAttribute('lang', L.lang === 'bn' ? 'bn' : 'en');
      root.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = L.t(el.getAttribute('data-i18n')); });
      root.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.setAttribute('placeholder', L.t(el.getAttribute('data-i18n-ph'))); });
      root.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.setAttribute('title', L.t(el.getAttribute('data-i18n-title'))); });
    },
    has: function (k) { return !!(dict.en[k]); }
  };

  return L;
